import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Derives the PostgreSQL Prisma schema from the SQLite development schema.
 *
 * Prisma requires a static datasource provider, so production (Postgres) and
 * local development (SQLite) need separate schema files. Running this script
 * keeps the Postgres copy byte-identical apart from the provider line.
 *
 * Usage: node tools/postgres-schema.mjs [--check]
 */
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = path.join(root, 'apps/api/prisma/schema.prisma')
const targetPath = path.join(root, 'apps/api/prisma/schema.postgres.prisma')
const marker = 'provider = "sqlite"'

const source = fs.readFileSync(sourcePath, 'utf8')
const occurrences = source.split(marker).length - 1
if (occurrences !== 1) {
  console.error(`Expected exactly one "${marker}" in ${sourcePath}, found ${occurrences}.`)
  process.exit(1)
}
const generated = `// Generated by tools/postgres-schema.mjs from schema.prisma — do not edit.\n${source.replace(marker, 'provider = "postgresql"')}`

if (process.argv.includes('--check')) {
  const current = fs.existsSync(targetPath) ? fs.readFileSync(targetPath, 'utf8') : ''
  if (current !== generated) {
    console.error('schema.postgres.prisma is out of date. Run: node tools/postgres-schema.mjs')
    process.exit(1)
  }
  console.log('PostgreSQL schema is in sync with schema.prisma.')
} else {
  fs.writeFileSync(targetPath, generated, 'utf8')
  console.log(`Wrote ${path.relative(root, targetPath)}`)
}
