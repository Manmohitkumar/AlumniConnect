export function isLocaleCode(value: unknown): value is LocaleCode {
  return typeof value === 'string' && LOCALES.some((entry) => entry.code === value)
}

export function localeDir(code: LocaleCode): 'ltr' | 'rtl' {
  return LOCALES.find((entry) => entry.code === code)?.dir ?? 'ltr'
}

function storedLocale(): LocaleCode {
  try {
    const value = localStorage.getItem(STORAGE_KEY)
    if (isLocaleCode(value)) return value
  } catch {
    // Storage can be unavailable in private modes; fall back to the browser.
  }
  const browser = typeof navigator !== 'undefined' ? navigator.language.slice(0, 2) : 'en'
  return isLocaleCode(browser) ? browser : 'en'
}

type I18nValue = {
  locale: LocaleCode
  dir: 'ltr' | 'rtl'
  t: (text: string, fallback?: string) => string
  setLocale: (code: LocaleCode, options?: { persist?: boolean }) => void
  formatNumber: (value: number) => string
}

const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<LocaleCode>(storedLocale)

  useEffect(() => {
    document.documentElement.lang = locale
    document.documentElement.dir = localeDir(locale)
    setFormatLocale(locale)
  }, [locale])

  const setLocale = useCallback((code: LocaleCode, options: { persist?: boolean } = { persist: true }) => {
    setLocaleState(code)
    try {
      localStorage.setItem(STORAGE_KEY, code)
    } catch {
      // Preference still applies for this session.
    }
    if (options.persist) apiPatch('/profile/me/preferences', { locale: code }).catch(() => null)
  }, [])

  const value = useMemo<I18nValue>(
    () => ({
      locale,
      dir: localeDir(locale),
      t: (text, fallback) => messages[locale][text] ?? fallback ?? text,
      setLocale,
      formatNumber: (input) => new Intl.NumberFormat(locale).format(input),
    }),
    [locale, setLocale],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}

/** Language picker shared by the dashboard shell and profile settings. */
export function LocaleSelect({
  value,
  onChange,
  className,
  id,
}: {
  value: LocaleCode
  onChange: (code: LocaleCode) => void
  className?: string
  id?: string
}) {
  const { t } = useI18n()
  return (
    <select id={id} className={className} value={value} onChange={(event) => onChange(event.target.value as LocaleCode)} aria-label={t('Interface language')}>
      {LOCALES.map((entry) => (
        <option key={entry.code} value={entry.code}>
          {entry.native} ({entry.label})
        </option>
      ))}
    </select>
  )
}
